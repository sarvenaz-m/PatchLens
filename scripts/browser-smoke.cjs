/* Optional real-browser checks. npm install --no-save playwright@1.62.1 first. */
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const {pathToFileURL}=require('node:url');

(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:process.env.PATCHLENS_CHROMIUM_PATH||undefined,args:process.env.PATCHLENS_NO_SANDBOX?['--no-sandbox']:[]});
  const directory=path.join(__dirname,'../artifacts/browser');fs.mkdirSync(directory,{recursive:true});
  const page=await browser.newPage({viewport:{width:1440,height:1080}});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  try {
    await page.goto(pathToFileURL(path.join(__dirname,'../index.html')).href);
    await page.locator('#view-overview .stats-grid').waitFor();
    assert.match(await page.locator('#experiment-id').textContent(),/^[a-z0-9]{16}$/);
    for(const route of ['overview','pairs','experiments','compare','diagnostics','embeddings','tools','review','provenance']) {
      await page.locator(`nav [data-route="${route}"]`).click();
      assert.equal(await page.locator(`#view-${route}`).isVisible(),true);
      await page.screenshot({path:path.join(directory,route+'.png'),fullPage:true});
    }
    assert.equal(await page.locator('#version').textContent(),'1.0.0');
    await page.locator('nav [data-route="diagnostics"]').click();
    assert.equal(await page.locator('.margin-row').count(),6);
    assert.equal(await page.locator('.cwe-button').count(),6);
    await page.locator('nav [data-route="compare"]').click();
    assert.match(await page.locator('.stat').filter({hasText:'Improved decisions'}).textContent(),/1/);
    const candidate=JSON.parse(fs.readFileSync(path.join(__dirname,'../examples/repeated-study/seed-29/report.json')));
    await page.locator('#comparison-file').setInputFiles({name:'candidate.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(candidate))});
    await page.waitForFunction(()=>document.querySelector('#toast').textContent.includes('Matched candidate'));
    assert.match(await page.locator('#view-compare').textContent(),new RegExp(candidate.experiment_id));
    const wrong=structuredClone(candidate);wrong.samples[0].code+=' // changed';
    await page.locator('#comparison-file').setInputFiles({name:'wrong.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(wrong))});
    await page.waitForFunction(()=>document.querySelector('#toast').textContent.includes('Source, labels or split'));
    await page.locator('#comparison-reset').click();
    const csvPromise=page.waitForEvent('download');await page.locator('#comparison-csv').click();
    const csvDownload=await csvPromise;assert.match(csvDownload.suggestedFilename(),/comparison.*\.csv$/);
    await page.locator('nav [data-route="review"]').click();
    const note='Checked source assumptions. <img src=x onerror="window.reviewXss=1">';
    await page.locator('#review-note').fill(note);
    await page.locator('nav [data-route="diagnostics"]').click();
    await page.locator('nav [data-route="review"]').click();
    assert.equal(await page.locator('#review-note').inputValue(),note);
    await page.locator('#review-status').selectOption('needs_attention');
    await page.locator('#review-form button[type="submit"]').click();
    assert.equal(await page.evaluate(()=>window.reviewXss),undefined);
    await page.reload();await page.locator('#review-note').waitFor();
    assert.equal(await page.locator('#review-note').inputValue(),note);
    assert.equal(await page.locator('#review-status').inputValue(),'needs_attention');
    const notesPromise=page.waitForEvent('download');await page.locator('#review-export').click();
    const notesDownload=await notesPromise;
    const notes=JSON.parse(fs.readFileSync(await notesDownload.path()));
    assert.equal(notes.entries[0].note,note);
    await page.locator('#review-filter').selectOption('reviewed');
    assert.equal(await page.locator('#review-form').count(),0);
    await page.locator('#review-filter').selectOption('all');
    notes.entries[0].note='Imported review backup';notes.entries[0].status='reviewed';notes.entries[0].updated_at=new Date(Date.now()+1000).toISOString();
    await page.locator('#review-file').setInputFiles({name:'review-backup.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(notes))});
    await page.waitForFunction(()=>document.querySelector('#toast').textContent.includes('1 newer review entries imported'));
    assert.equal(await page.locator('#review-note').inputValue(),'Imported review backup');
    assert.equal(await page.locator('#review-count').textContent(),'1');
    await page.locator('#command-button').click();
    assert.equal(await page.locator('#command-dialog').isVisible(),true);
    await page.locator('#command-search').fill('Diagnostics');
    await page.locator('#command-search').press('Enter');
    assert.equal(await page.locator('#view-diagnostics').isVisible(),true);
    assert.equal(await page.locator('#command-dialog').isVisible(),false);
    await page.keyboard.press('Control+k');
    await page.locator('#command-search').fill('configuration');
    await page.locator('#command-search').press('ArrowDown');
    await page.keyboard.press('Enter');
    assert.equal(await page.locator('#view-pairs').isVisible(),true);
    assert.match(await page.locator('#pair-detail h2').textContent(),/configuration/);
    await page.locator('nav [data-route="pairs"]').click();
    await page.locator('#pair-search').fill('NO-SUCH-PAIR-123');
    assert.match(await page.locator('#pair-list').textContent(),/No matching/);
    await page.locator('#pair-search').fill('');
    await page.locator('#cwe-filter').selectOption('CWE-79');
    assert.equal(await page.locator('.code-panel').count(),2);
    await page.locator('nav [data-route="experiments"]').click();
    await page.locator('#threshold-slider').fill('0.9');
    await page.locator('#threshold-slider').dispatchEvent('change');
    assert.equal(await page.locator('#notice').isVisible(),true);
    await page.locator('[data-reset-threshold]').click();
    assert.equal(await page.locator('#notice').isVisible(),false);
    await page.locator('#model-select').selectOption('linear');
    await page.locator('#split-select').selectOption('validation');
    await page.locator('nav [data-route="embeddings"]').click();
    assert.equal(await page.locator('.scatter-point').count(),12);
    await page.locator('.scatter-point').first().focus();await page.keyboard.press('Enter');
    assert.equal(await page.locator('.point-inspector h3').count(),1);
    await page.locator('#theme-toggle').click();
    assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
    await page.screenshot({path:path.join(directory,'dark.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    for(const route of ['overview','pairs','experiments','compare','diagnostics','embeddings','tools','review','provenance']) {
      await page.locator(`nav [data-route="${route}"]`).click();
      const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+1);
      assert.equal(overflow,false,`Horizontal overflow at 390px on ${route}`);
    }
    await page.screenshot({path:path.join(directory,'mobile.png'),fullPage:true});
    const report=JSON.parse(fs.readFileSync(path.join(__dirname,'../examples/fixture-run/report.json')));
    report.samples.forEach(s=>s.title='<img src=x onerror="window.patchlensXss=1">');
    await page.locator('#import-file').setInputFiles({name:'local-report.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(report))});
    await page.locator('nav [data-route="pairs"]').click();
    assert.equal(await page.locator('#pair-detail img').count(),0);
    assert.equal(await page.evaluate(()=>window.patchlensXss),undefined);
    const downloadPromise=page.waitForEvent('download');await page.locator('#export-button').click();
    const download=await downloadPromise;assert.match(download.suggestedFilename(),/^patchlens-.*\.json$/);
    assert.deepEqual(errors,[]);
    console.log('Browser smoke checks passed. Screenshots: artifacts/browser/');
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
